from typing import Protocol, List, Optional
from uuid import UUID
from app.domain.entities.knowledge_source import KnowledgeSource

class KnowledgeSourceRepository(Protocol):
    async def get_by_id(self, source_id: UUID) -> Optional[KnowledgeSource]: ...
    async def search_similar(self, embedding: List[float], limit: int = 5) -> List[KnowledgeSource]: ...
    async def create(self, source: KnowledgeSource) -> KnowledgeSource: ...
    async def list_all(self) -> List[KnowledgeSource]: ...
