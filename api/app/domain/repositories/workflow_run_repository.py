from typing import Protocol, List, Optional
from uuid import UUID
from app.domain.entities.workflow_run import WorkflowRun

class WorkflowRunRepository(Protocol):
    async def get_by_id(self, run_id: UUID) -> Optional[WorkflowRun]: ...
    async def get_by_case_id(self, case_id: UUID) -> List[WorkflowRun]: ...
    async def create(self, workflow_run: WorkflowRun) -> WorkflowRun: ...
    async def update(self, workflow_run: WorkflowRun) -> WorkflowRun: ...
